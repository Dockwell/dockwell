// Generates src/styles/tokens.css and src/tokens.ts from
// design/system/tokens.json, the design system's source of truth.
//
//   pnpm --filter @dockwell/ui tokens          write the files
//   pnpm --filter @dockwell/ui tokens:check    fail if they are stale (CI)
//
// Light is the first theme and the fallback. Dark follows the system unless a
// theme is chosen with data-theme on an ancestor.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

type Themed = string | Record<string, string>;
interface Token {
  name: string;
  value: Themed;
  usage?: string;
}
interface TextStyle {
  name: string;
  fontSize: string;
  lineHeight: string;
  fontWeight: number;
  letterSpacing?: string;
  usage?: string;
}
interface Tokens {
  color: { themes: { id: string; name: string }[]; tokens: Token[] };
  type: {
    fonts: { family: string; file: string; weight: string; style?: string }[];
    families: Record<string, string>;
    groups: { name: string; family: string; styles: TextStyle[] }[];
  };
  spacing: { tokens: Token[] };
  radius: { tokens: Token[] };
  size: { tokens: Token[] };
  shadow: { tokens: Token[] };
  zIndex: { tokens: Token[] };
}

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoDir = join(pkgDir, "..", "..");
const sourcePath = join(repoDir, "design/system/tokens.json");
const cssPath = join(pkgDir, "src/styles/tokens.css");
const tsPath = join(pkgDir, "src/tokens.ts");

const header = (comment: (s: string) => string) =>
  [
    comment("SPDX-License-Identifier: AGPL-3.0-only"),
    comment("Generated by packages/ui/scripts/build-tokens.ts from design/system/tokens.json."),
    comment("Don't edit: change the design system, then run `pnpm --filter @dockwell/ui tokens`."),
  ].join("\n");

const aliasPattern = /^\{([A-Za-z0-9][A-Za-z0-9_.-]*)\}$/;

/** A token's value in one theme; a missing theme inherits the first one's. */
function valueIn(token: Token, theme: string, first: string): string {
  if (typeof token.value === "string") return token.value;
  return token.value[theme] ?? token.value[first] ?? "";
}

function cssValue(value: string): string {
  const alias = aliasPattern.exec(value);
  return alias ? `var(--${alias[1]})` : value;
}

/** Resolves aliases to concrete values, for the TypeScript export. */
function resolve(
  byName: Map<string, Token>,
  token: Token,
  theme: string,
  first: string,
  seen = new Set<string>(),
): string {
  const value = valueIn(token, theme, first);
  const alias = aliasPattern.exec(value);
  if (!alias) return value;
  const target = byName.get(alias[1] ?? "");
  if (!target || seen.has(target.name)) {
    throw new Error(`token ${token.name} aliases ${value}, which doesn't resolve`);
  }
  seen.add(token.name);
  return resolve(byName, target, theme, first, seen);
}

function usage(token: { usage?: string }): string {
  return token.usage ? ` /* ${token.usage.replaceAll("*/", "* /")} */` : "";
}

function camel(name: string): string {
  return name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

function px(value: string): number {
  const n = Number.parseFloat(value);
  if (!value.endsWith("px") || Number.isNaN(n)) throw new Error(`expected a px value, got ${value}`);
  return n;
}

export function generate(tokens: Tokens): { css: string; ts: string } {
  const themes = tokens.color.themes.map((t) => t.id);
  const [first, ...rest] = themes;
  if (!first) throw new Error("tokens.json defines no colour themes");
  if (rest.length !== 1 || rest[0] !== "dark" || first !== "light") {
    throw new Error(`expected the themes light and dark, got ${themes.join(", ")}`);
  }
  const themed = [...tokens.color.tokens, ...tokens.shadow.tokens];
  const byName = new Map(tokens.color.tokens.map((t) => [t.name, t]));
  const fontRel = relative(dirname(cssPath), join(repoDir, "design/system")).replaceAll("\\", "/");

  const themeBlock = (theme: string, withUsage: boolean, indent: string) =>
    [
      `${indent}color-scheme: ${theme};`,
      ...themed.map((t) => `${indent}--${t.name}: ${cssValue(valueIn(t, theme, first))};${withUsage ? usage(t) : ""}`),
    ].join("\n");

  const scalar = (family: Token[]) => family.map((t) => `  --${t.name}: ${t.value as string};${usage(t)}`);

  const textStyles = tokens.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family })));
  const css = [
    `/* ${header((s) => s).replaceAll("\n", "\n   ")} */`,
    "",
    ...tokens.type.fonts.map(
      (f) =>
        `@font-face { font-family: "${f.family}"; src: url("${fontRel}/${f.file}") format("woff2"); ` +
        `font-weight: ${f.weight}; font-style: ${f.style ?? "normal"}; font-display: swap; }`,
    ),
    "",
    ":root {",
    ...Object.entries(tokens.type.families).map(([k, v]) => `  --font-${k}: ${v};`),
    ...scalar(tokens.spacing.tokens),
    ...scalar(tokens.radius.tokens),
    ...scalar(tokens.size.tokens),
    ...scalar(tokens.zIndex.tokens),
    ...textStyles.flatMap((s) => [
      `  --text-${s.name}: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${s.family});${usage(s)}`,
      `  --text-${s.name}-tracking: ${s.letterSpacing ?? "normal"};`,
    ]),
    "}",
    "",
    "/* Light: the default, and the fallback. */",
    ':root, [data-theme="light"] {',
    themeBlock("light", true, "  "),
    "}",
    "",
    "/* Dark: follows the system unless a theme is chosen. */",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    themeBlock("dark", false, "    "),
    "  }",
    "}",
    '[data-theme="dark"] {',
    themeBlock("dark", false, "  "),
    "}",
    "",
    ...textStyles.map(
      (s) => `.dw-text-${s.name} { font: var(--text-${s.name}); letter-spacing: var(--text-${s.name}-tracking); }`,
    ),
    "",
  ].join("\n");

  const colorsIn = (theme: string) =>
    Object.fromEntries(tokens.color.tokens.map((t) => [t.name, resolve(byName, t, theme, first)]));
  const scalarMap = (family: Token[], parse: (v: string) => number | string) =>
    Object.fromEntries(family.map((t) => [t.name, parse(t.value as string)]));

  const json = (v: unknown) => JSON.stringify(v, null, 2);
  const ts = [
    header((s) => `// ${s}`),
    "",
    "/** Colour tokens per theme, with aliases resolved. Prefer the CSS variables; use these for canvas and charts. */",
    `export const colors = ${json({ light: colorsIn("light"), dark: colorsIn("dark") })} as const;`,
    "",
    "export type Theme = keyof typeof colors;",
    'export type ColorToken = keyof (typeof colors)["light"];',
    "",
    "/** Spacing in px, on the 4px grid. */",
    `export const space = ${json(scalarMap(tokens.spacing.tokens, px))} as const;`,
    "",
    "/** Corner radii in px. */",
    `export const radius = ${json(scalarMap(tokens.radius.tokens, px))} as const;`,
    "",
    "/** Fixed sizes for controls and layout regions, in px. */",
    `export const size = ${json(scalarMap(tokens.size.tokens, px))} as const;`,
    "",
    "/** Layer order, lowest to highest. */",
    `export const zIndex = ${json(scalarMap(tokens.zIndex.tokens, Number))} as const;`,
    "",
    "/** Font stacks. */",
    `export const fonts = ${json(tokens.type.families)} as const;`,
    "",
    "/** Text styles; each also exists as the class dw-text-<name> and the variable --text-<name>. */",
    `export const textStyles = ${json(
      Object.fromEntries(
        textStyles.map((s) => [
          camel(s.name),
          {
            className: `dw-text-${s.name}`,
            fontFamily: s.family,
            fontSize: px(s.fontSize),
            lineHeight: px(s.lineHeight),
            fontWeight: s.fontWeight,
            letterSpacing: s.letterSpacing ?? "normal",
          },
        ]),
      ),
    )} as const;`,
    "",
  ].join("\n");

  return { css, ts };
}

function main(): void {
  const check = process.argv.includes("--check");
  const { css, ts } = generate(JSON.parse(readFileSync(sourcePath, "utf8")) as Tokens);
  const outputs: [string, string][] = [
    [cssPath, css],
    [tsPath, ts],
  ];
  const stale = outputs.filter(([path, content]) => {
    try {
      return readFileSync(path, "utf8") !== content;
    } catch {
      return true;
    }
  });
  if (check) {
    if (stale.length > 0) {
      const names = stale.map(([p]) => relative(repoDir, p)).join(" and ");
      console.error(
        `${names} ${stale.length > 1 ? "are" : "is"} out of date. Run pnpm --filter @dockwell/ui tokens and commit the result.`,
      );
      process.exit(1);
    }
    return;
  }
  for (const [path, content] of stale) {
    writeFileSync(path, content);
    console.log(`wrote ${relative(repoDir, path)}`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
