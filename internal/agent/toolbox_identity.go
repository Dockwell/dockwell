const (
	toolboxHostIdentity = " # Dockwell hostname"
	toolboxCloudConfig  = "/etc/cloud/cloud.cfg.d/zz-dockwell-toolbox.cfg"
)

func (t *hostToolbox) usingSystemdTool(tool hosttool.Tool) bool {
	_, found := t.tools.Find(tool)
	return found && t.systemd()
}

func (t *hostToolbox) hostname(ctx context.Context) string {
	if t.usingSystemdTool(toolboxHostname) {
		if raw, err := t.run(ctx, toolboxHostname, "--static"); err == nil && strings.TrimSpace(string(raw)) != "" {
			return strings.TrimSpace(string(raw))
		}
	}
	raw, err := t.read("/etc/hostname")
	if err == nil {
		return strings.TrimSpace(string(raw))
	}
	if t.tools.Root == "" {
		name, _ := os.Hostname()
		return name
	}
	return ""
}

func (t *hostToolbox) planHostname(ctx context.Context, edit *toolboxEdit, name string) error {
	if !toolboxValidHostname(name) || len(name) > 64 {
		return errors.New("enter a hostname of up to 64 characters, using letters, numbers, dots and hyphens")
	}
	old := t.hostname(ctx)
	if !toolboxValidHostname(old) || len(old) > 64 {
		return errors.New("the current hostname can't be restored safely. Set a valid hostname on the server first")
	}
	hostname, err := t.file("/etc/hostname", 0o644)
	if err != nil {
		return err
	}
	hostname.next = []byte(name + "\n")
	hosts, err := t.file("/etc/hosts", 0o644)
	if err != nil {
		return err
	}
	hosts.next, err = toolboxEditHosts(toolboxRenameHost(hosts.old, old, name), name, "127.0.1.1", toolboxHostIdentity)
	if err != nil {
		return err
	}
	if err := t.planCloudIdentity(edit, hosts.old, true); err != nil {
		return err
	}
	edit.files = append(edit.files, hostname, hosts)
	toolboxDifference(edit.plan, "Hostname", old, name)
	toolboxDifference(edit.plan, "/etc/hosts", "", "127.0.1.1 "+name)
	edit.apply = func(ctx context.Context) error {
		if t.usingSystemdTool(toolboxHostname) {
			_, err := t.run(ctx, toolboxHostname, "set-hostname", name)
			return err
		}
		if t.tools.Root == "" {
			return unix.Sethostname([]byte(name))
		}
		return nil
	}
	return nil
}

func toolboxRenameHost(raw []byte, old, name string) []byte {
	var out strings.Builder
	for line := range strings.SplitAfterSeq(string(raw), "\n") {
		base, comment, hasComment := strings.Cut(strings.TrimSuffix(line, "\n"), "#")
		fields := strings.Fields(base)
		if len(fields) < 2 || fields[0] != "127.0.1.1" || strings.HasSuffix(strings.TrimSuffix(line, "\n"), toolboxHostIdentity) {
			out.WriteString(line)
			continue
		}
		oldShort, _, _ := strings.Cut(old, ".")
		isOld := func(s string) bool { return strings.EqualFold(s, old) || strings.EqualFold(s, oldShort) }
		if !slices.ContainsFunc(fields[1:], isOld) {
			out.WriteString(line)
			continue
		}
		// Keep aliases and comments while replacing the distribution's old name.
		aliases := slices.DeleteFunc(fields[1:], func(s string) bool {
			return isOld(s) || strings.EqualFold(s, name)
		})
		out.WriteString("127.0.1.1 " + name)
		if len(aliases) != 0 {
			out.WriteString(" " + strings.Join(aliases, " "))
		}
		if hasComment {
			out.WriteString(" #" + comment)
		}
		out.WriteByte('\n')
	}
	return []byte(out.String())
}

// Cloud-init's top-level keys are read in file order, as cloud-init merges its
// config. Refuse unfamiliar values rather than writing an ineffective override.
func (t *hostToolbox) planCloudIdentity(edit *toolboxEdit, hosts []byte, rename bool) error {
	if _, err := os.Stat(t.path("/etc/cloud/cloud-init.disabled")); err == nil {
		return nil
	}
	names, err := filepath.Glob(t.path("/etc/cloud/cloud.cfg.d/*.cfg"))
	if err != nil {
		return err
	}
	names = append([]string{t.path("/etc/cloud/cloud.cfg")}, names...)
	values := map[string]string{}
	var installed bool
	header := strings.ToLower(string(hosts))
	managedHeader := strings.Contains(header, "manage_etc_hosts") || strings.Contains(header, "generated by cloud-init")
	for _, path := range names {
		name := strings.TrimPrefix(path, t.tools.Root)
		raw, err := t.read(name)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return err
		}
		installed = true
		for line := range strings.SplitSeq(string(raw), "\n") {
			line, _, _ = strings.Cut(line, "#")
			if line != strings.TrimLeft(line, " \t") {
				continue
			}
			key, value, _ := strings.Cut(line, ":")
			key = strings.TrimSpace(key)
			if key != "preserve_hostname" && key != "manage_etc_hosts" {
				continue
			}
			value = strings.ToLower(strings.Trim(strings.TrimSpace(value), `"'`))
			switch value {
			case "true", "yes", "on", "1", "false", "no", "off", "0", "localhost":
			default:
				return fmt.Errorf("cloud-init manages host identity through %s. Review its %s setting before changing host identity", name, key)
			}
			if name > toolboxCloudConfig && (key == "manage_etc_hosts" && toolboxCloudTrue(value) ||
				key == "preserve_hostname" && rename && !toolboxCloudTrue(value)) {
				return fmt.Errorf("%s overrides cloud-init's host identity settings. Move that override before planning", name)
			}
			values[key] = value
		}
	}
	changeHostname := rename && installed && !toolboxCloudTrue(values["preserve_hostname"])
	changeHosts := toolboxCloudTrue(values["manage_etc_hosts"]) || values["manage_etc_hosts"] == "" && managedHeader
	if !changeHostname && !changeHosts {
		return nil
	}
	w, err := t.optionalConfig(toolboxCloudConfig)
	if err != nil {
		return err
	}
	if !w.wasMissing && !strings.HasPrefix(string(w.old), toolboxUnitMarker) {
		return fmt.Errorf("%s is already in use. Move the existing cloud-init override before planning", w.path)
	}
	w.next = []byte(toolboxUnitMarker)
	if changeHostname || strings.Contains(string(w.old), "preserve_hostname: true") {
		w.next = append(w.next, "preserve_hostname: true\n"...)
	}
	if changeHosts || strings.Contains(string(w.old), "manage_etc_hosts: false") {
		w.next = append(w.next, "manage_etc_hosts: false\n"...)
	}
	edit.files = append(edit.files, w)
	toolboxDifference(edit.plan, "cloud-init host identity", "cloud-init manages these settings", w.path)
	return nil
}

func toolboxCloudTrue(value string) bool {
	return slices.Contains([]string{"true", "yes", "on", "1", "localhost"}, value)
}

func toolboxOwnHost(line string) (name, addr string) {
	before, ok := strings.CutSuffix(line, toolboxHostsMark)
	if !ok {
		return "", ""
	}
	f := strings.Fields(before)
	if len(f) != 2 || !toolboxValidHostname(f[1]) {
		return "", ""
	}
	if _, err := netip.ParseAddr(f[0]); err != nil {
		return "", ""
	}
	return f[1], f[0]
}

func toolboxEditHosts(raw []byte, name, addr, mark string) ([]byte, error) {
	var out strings.Builder
	var existing string
	for line := range strings.SplitAfterSeq(string(raw), "\n") {
		text := strings.TrimSuffix(line, "\n")
		base, _, _ := strings.Cut(text, "#")
		fields := strings.Fields(base)
		switch {
		case strings.HasSuffix(text, toolboxHostIdentity) && mark == toolboxHostIdentity && len(fields) == 2,
			strings.HasSuffix(text, toolboxHostsMark) && mark == toolboxHostsMark && len(fields) == 2 && strings.EqualFold(fields[1], name):
			continue
		case len(fields) > 1 && addr != "" && slices.ContainsFunc(fields[1:], func(s string) bool { return strings.EqualFold(name, s) }):
			if mark == toolboxHostsMark || fields[0] != addr {
				return nil, fmt.Errorf("%s is already in /etc/hosts at %s. Choose a different name", name, fields[0])
			}
			existing = fields[0]
		}
		out.WriteString(line)
	}
	if addr != "" && existing == "" {
		if out.Len() != 0 && !strings.HasSuffix(out.String(), "\n") {
			out.WriteByte('\n')
		}
		fmt.Fprintf(&out, "%s %s%s\n", addr, name, mark)
	}
	return []byte(out.String()), nil
}

func (t *hostToolbox) planHosts(edit *toolboxEdit, ask *v1.ToolboxHosts) error {
	name, addr := ask.GetHostname(), ask.GetAddress()
	if !toolboxValidHostname(name) {
		return errors.New("enter a valid hostname for /etc/hosts")
	}
	if addr != "" {
		ip, err := netip.ParseAddr(addr)
		if err != nil || ip.Zone() != "" || ip.IsUnspecified() || ip.IsMulticast() {
			return errors.New("enter a valid IP address for /etc/hosts")
		}
		addr = ip.String()
	}
	w, err := t.file("/etc/hosts", 0o644)
	if err != nil {
		return err
	}
	var old string
	for line := range strings.SplitSeq(string(w.old), "\n") {
		n, ip := toolboxOwnHost(line)
		if strings.EqualFold(n, name) {
			old = ip
		}
	}
	if addr == "" && old == "" {
		return errors.New("there is no Dockwell-owned entry for this hostname")
	}
	w.next, err = toolboxEditHosts(w.old, name, addr, toolboxHostsMark)
	if err != nil {
		return err
	}
	if err := t.planCloudIdentity(edit, w.old, false); err != nil {
		return err
	}
	edit.files = append(edit.files, w)
	toolboxDifference(edit.plan, name+" in /etc/hosts", old, addr)
	return nil
}

func (t *hostToolbox) timezone(ctx context.Context) string {
	if t.usingSystemdTool(toolboxTime) {
		if raw, err := t.run(ctx, toolboxTime, "show", "--property=Timezone", "--value"); err == nil {
			return strings.TrimSpace(string(raw))
		}
	}
	if link, err := os.Readlink(t.path("/etc/localtime")); err == nil {
		if _, zone, ok := strings.Cut(link, "zoneinfo/"); ok {
			return zone
		}
	}
	raw, _ := t.read("/etc/timezone")
	return strings.TrimSpace(string(raw))
}

var toolboxZone = toolboxPattern(`^[A-Za-z0-9_+.-]+(?:/[A-Za-z0-9_+.-]+)*$`)

// zone.tab is available even when the host runs without timedated.
func (t *hostToolbox) timezones(ctx context.Context) []string {
	if t.usingSystemdTool(toolboxTime) {
		if raw, err := t.run(ctx, toolboxTime, "list-timezones", "--no-pager"); err == nil {
			return strings.Fields(string(raw))
		}
	}
	out := []string{"UTC"}
	raw, _ := t.read("/usr/share/zoneinfo/zone.tab")
	for line := range strings.SplitSeq(string(raw), "\n") {
		if strings.HasPrefix(line, "#") {
			continue
		}
		if f := strings.Fields(line); len(f) >= 3 && toolboxZone().MatchString(f[2]) {
			out = append(out, f[2])
		}
	}
	slices.Sort(out)
	return slices.Compact(out)
}

func (t *hostToolbox) planTimezone(ctx context.Context, edit *toolboxEdit, zone string) error {
	if len(zone) > 128 || !toolboxZone().MatchString(zone) || !slices.Contains(t.timezones(ctx), zone) {
		return errors.New("choose a time zone installed on this server")
	}
	toolboxDifference(edit.plan, "Time zone", t.timezone(ctx), zone)
	if t.usingSystemdTool(toolboxTime) {
		edit.apply = func(ctx context.Context) error {
			_, err := t.run(ctx, toolboxTime, "set-timezone", zone)
			return err
		}
		return nil
	}
	if err := t.trustedParent("/etc/localtime"); err != nil {
		return err
	}
	w, err := t.file("/etc/timezone", 0o644)
	if err != nil {
		return err
	}
	w.next = []byte(zone + "\n")
	edit.files = []toolboxWrite{w}
	edit.apply = func(context.Context) error {
		dir, err := os.MkdirTemp(t.path("/etc"), ".dockwell-timezone-")
		if err != nil {
			return err
		}
		defer os.RemoveAll(dir)
		link := filepath.Join(dir, "localtime")
		if err := os.Symlink("/usr/share/zoneinfo/"+zone, link); err != nil {
			return err
		}
		return os.Rename(link, t.path("/etc/localtime"))
	}
	return nil
}

func (t *hostToolbox) ntp(ctx context.Context) (available, enabled, synced bool) {
	if t.usingSystemdTool(toolboxTime) {
		raw, err := t.run(ctx, toolboxTime, "show", "--property=CanNTP", "--property=NTP", "--property=NTPSynchronized")
		if err != nil {
			return false, false, false
		}
		lines := strings.Fields(string(raw))
		return slices.Contains(lines, "CanNTP=yes"), slices.Contains(lines, "NTP=yes"), slices.Contains(lines, "NTPSynchronized=yes")
	}
	service := t.ntpOpenRC()
	if service == "" {
		return false, false, false
	}
	_, enabledErr := os.Lstat(t.path("/etc/runlevels/default/" + service))
	var clock unix.Timex
	if t.tools.Root == "" {
		_, err := unix.Adjtimex(&clock)
		synced = err == nil && clock.Status&unix.STA_UNSYNC == 0
	}
	return true, enabledErr == nil, synced
}

func (t *hostToolbox) ntpOpenRC() string {
	if _, ok := t.tools.Find(toolboxTool("rc-update")); !ok {
		return ""
	}
	var choices []string
	for _, name := range []string{"chronyd", "ntpd", "openntpd"} {
		if fi, err := os.Stat(t.path("/etc/init.d/" + name)); err == nil && fi.Mode().IsRegular() {
			choices = append(choices, name)
		}
	}
	if len(choices) == 1 {
		return choices[0]
	}
	return ""
}

func (t *hostToolbox) planNTP(ctx context.Context, edit *toolboxEdit, enabled bool) error {
	available, old, _ := t.ntp(ctx)
	if !available {
		return errors.New("this server has no supported time synchronization service")
	}
	toolboxDifference(edit.plan, "NTP", strconv.FormatBool(old), strconv.FormatBool(enabled))
	if t.usingSystemdTool(toolboxTime) {
		edit.apply = func(ctx context.Context) error {
			_, err := t.run(ctx, toolboxTime, "set-ntp", strconv.FormatBool(enabled))
			return err
		}
		return nil
	}
	name := t.ntpOpenRC()
	toolboxDifference(edit.plan, "OpenRC service", name, name)
	edit.apply = func(ctx context.Context) error {
		boot, runtime, rollback := "del", "stop", "add"
		if enabled {
			boot, runtime, rollback = "add", "start", "del"
		}
		if old != enabled {
			if _, err := t.run(ctx, toolboxTool("rc-update"), boot, name, "default"); err != nil {
				return err
			}
		}
		_, err := t.run(ctx, toolboxTool("rc-service"), name, runtime)
		if err != nil && old != enabled {
			_, back := t.run(context.WithoutCancel(ctx), toolboxTool("rc-update"), rollback, name, "default")
			return errors.Join(err, back)
		}
		return err
	}
	return nil
}
