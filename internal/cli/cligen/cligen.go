// Package cligen writes the dockwell CLI's API commands from the schema, as
// the protoc plugin protoc-gen-dockwell-cli. It describes each method of
// dockwell.v1 as a command, dockwell <noun> <verb>, with a flag for each
// field of its request and help from the schema's comments, and each kind
// of resource as dockwell <kinds> create, update and delete. What the
// commands do is shared machinery, in internal/cli/apicli; nothing about a
// method is written by hand. See
// docs/adr/0019-a-cli-generated-from-the-schema.md.
package cligen

import (
	"fmt"
	"slices"
	"strconv"
	"strings"
	"unicode"

	"google.golang.org/genproto/googleapis/api/annotations"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/reflect/protoregistry"
	"google.golang.org/protobuf/types/dynamicpb"
	"google.golang.org/protobuf/types/pluginpb"
)

// Where the generated code goes, and what it uses.
const (
	// Package is the API package that gets commands.
	Package = "dockwell.v1"
	// OutputFile is the generated file, in the directory buf writes to.
	OutputFile = "apicmd.gen.go"
	// ImportPath is the generated package's.
	ImportPath      = protogen.GoImportPath("github.com/dockwell/dockwell/internal/cli/apicmd")
	apicli          = protogen.GoImportPath("github.com/dockwell/dockwell/internal/cli/apicli")
	connectPackage  = "connect"
	editMessage     = "dockwell.v1.Edit"
	effectOption    = "dockwell.v1.effect"
	commandOption   = "dockwell.v1.command"
	nounsOption     = "dockwell.v1.nouns"
	flagOption      = "dockwell.v1.flag"
	sensitiveOption = "dockwell.resource.v1alpha1.sensitive"
	effectNone      = "EFFECT_UNSPECIFIED"
	editSpecField   = "spec"
	specKindsOneof  = "kind"
	wrapWidth       = 80
	headerLicense   = "// SPDX-License-Identifier: AGPL-3.0-only"
	generatedNotice = "// Code generated by protoc-gen-dockwell-cli. DO NOT EDIT."
)

// Method is one method's command, as the generator names and describes it.
type Method struct {
	Method *protogen.Method
	Noun   string
	Verb   string
	// HTTP is the method's REST rule, such as "GET /v1/servers". Empty
	// for a stream.
	HTTP string
	// Effect is the name of the method's (dockwell.v1.effect), such as
	// "EFFECT_READ".
	Effect string
	// EffectIdent is that value's Go name.
	EffectIdent protogen.GoIdent
	// Package is the Go package of the method's file, where connect-go
	// puts its client beside the messages.
	Package     protogen.GoImportPath
	PackageName protogen.GoPackageName
	Short       string
	Long        string
	Fields      []Field
}

// Field is a flag or argument, from a field of a request or a spec.
type Field struct {
	// Path is the field's name, or for a field of a kind's spec, the path
	// to it, such as "app.image".
	Path string
	// Flag is the field's (dockwell.v1.flag), the flag it takes in place
	// of its name. Empty for most.
	Flag      string
	Help      string
	Arg       bool
	Sensitive bool
}

// Kind is one kind of resource's commands.
type Kind struct {
	// Field is the field of the spec that holds the kind, such as
	// "firewall_rule".
	Field  string
	Noun   string
	Short  string
	Long   string
	Fields []Field
}

// Noun is a noun's own help.
type Noun struct {
	Name  string
	Short string
	Long  string
}

// Generate writes the commands for every method of dockwell.v1 in the
// request, and for every kind in the spec an Edit carries.
func Generate(p *protogen.Plugin) error {
	p.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
	methods, nouns, err := Methods(p)
	if err != nil {
		return err
	}
	if len(methods) == 0 {
		return nil
	}
	kinds, err := Kinds(p)
	if err != nil {
		return err
	}
	g := p.NewGeneratedFile(OutputFile, ImportPath)
	write(g, methods, nouns, kinds)
	return nil
}

// schema reads the custom options the generator needs, which the plugin
// can't know as Go types: it runs while buf has emptied gen/. They come
// from the descriptors in the request instead.
type schema struct {
	plugin *protogen.Plugin
	types  *dynamicpb.Types
}

func newSchema(p *protogen.Plugin) (*schema, error) {
	files := new(protoregistry.Files)
	for _, f := range p.Files {
		if _, err := files.FindFileByPath(f.Desc.Path()); err == nil {
			continue
		}
		if err := files.RegisterFile(f.Desc); err != nil {
			return nil, fmt.Errorf("can't read %s: %w", f.Desc.Path(), err)
		}
	}
	return &schema{plugin: p, types: dynamicpb.NewTypes(files)}, nil
}

// option reads an option of a descriptor, or reports that it isn't set.
func (s *schema) option(d protoreflect.Descriptor, name protoreflect.FullName) (protoreflect.Value, protoreflect.ExtensionTypeDescriptor, bool) {
	xt, err := s.types.FindExtensionByName(name)
	if err != nil {
		return protoreflect.Value{}, nil, false
	}
	raw, err := proto.Marshal(d.Options())
	if err != nil {
		return protoreflect.Value{}, nil, false
	}
	opts := d.Options().ProtoReflect().New()
	if err := (proto.UnmarshalOptions{Resolver: s.types}).Unmarshal(raw, opts.Interface()); err != nil {
		return protoreflect.Value{}, nil, false
	}
	xd := xt.TypeDescriptor()
	if !opts.Has(xd) {
		return protoreflect.Value{}, xd, false
	}
	return opts.Get(xd), xd, true
}

// flag is a field's (dockwell.v1.flag), or empty when it has none.
func (s *schema) flag(fd protoreflect.FieldDescriptor) string {
	if v, _, ok := s.option(fd, flagOption); ok {
		return v.String()
	}
	return ""
}

// goIdent is the Go name of a descriptor's enum value, in the package of
// its file.
func (s *schema) goIdent(enum protoreflect.EnumDescriptor, value protoreflect.EnumValueDescriptor) protogen.GoIdent {
	f := s.plugin.FilesByPath[enum.ParentFile().Path()]
	return f.GoImportPath.Ident(string(enum.Name()) + "_" + string(value.Name()))
}

// Methods describes each method of dockwell.v1 in the request as a
// command, and each noun, sorted by noun and verb. It fails when two
// methods would have one command.
func Methods(p *protogen.Plugin) ([]Method, []Noun, error) {
	s, err := newSchema(p)
	if err != nil {
		return nil, nil, err
	}
	var out []Method
	services := map[string]*protogen.Service{}
	nounsOf := map[*protogen.Service][]string{}
	for _, f := range p.Files {
		if !f.Generate || f.Desc.Package() != Package {
			continue
		}
		for _, svc := range f.Services {
			for _, m := range svc.Methods {
				c, err := s.describe(f, m)
				if err != nil {
					return nil, nil, err
				}
				if _, ok := services[c.Noun]; !ok {
					services[c.Noun] = svc
				}
				if !slices.Contains(nounsOf[svc], c.Noun) {
					nounsOf[svc] = append(nounsOf[svc], c.Noun)
				}
				out = append(out, c)
			}
		}
	}
	order := map[*protogen.Method]int{}
	for i, m := range out {
		order[m.Method] = i
	}
	// Help names commands where the comments name methods: "Follow them
	// with WatchChange" is "Follow them with dockwell changes watch".
	names := commandNames(out)
	for i := range out {
		m := &out[i]
		m.Short, m.Long = names.Replace(m.Short), reflow(names.Replace(m.Long))
		for j := range m.Fields {
			m.Fields[j].Help = names.Replace(m.Fields[j].Help)
		}
	}
	slices.SortFunc(out, func(a, b Method) int {
		return strings.Compare(a.Noun+" "+a.Verb, b.Noun+" "+b.Verb)
	})
	for i := 1; i < len(out); i++ {
		if out[i].Noun == out[i-1].Noun && out[i].Verb == out[i-1].Verb {
			return nil, nil, fmt.Errorf("%s and %s would both be dockwell %s %s. Name one apart with the (dockwell.v1.command) option",
				out[i-1].Method.Desc.FullName(), out[i].Method.Desc.FullName(), out[i].Noun, out[i].Verb)
		}
	}
	var nouns []Noun
	for i := 0; i < len(out); {
		j := i
		for j < len(out) && out[j].Noun == out[i].Noun {
			j++
		}
		name := out[i].Noun
		help, err := s.nounHelp(services[name], name, nounsOf[services[name]])
		if err != nil {
			return nil, nil, err
		}
		nouns = append(nouns, Noun{
			Name:  name,
			Short: nounShort(name, out[i:j], order),
			Long:  reflow(names.Replace(help)),
		})
		i = j
	}
	return out, nouns, nil
}

// nounHelp is a noun's help: its service's comment, when the service's
// methods' commands have that noun alone, and otherwise what the service's
// (dockwell.v1.nouns) says of it, as a comment that describes the whole
// service fits none of its nouns.
func (s *schema) nounHelp(svc *protogen.Service, noun string, nouns []string) (string, error) {
	helps := map[string]string{}
	if v, _, ok := s.option(svc.Desc, nounsOption); ok {
		entries := v.List()
		for i := range entries.Len() {
			m := entries.Get(i).Message()
			fields := m.Descriptor().Fields()
			name, help := m.Get(fields.ByName("name")).String(), strings.TrimSpace(m.Get(fields.ByName("help")).String())
			if !slices.Contains(nouns, name) {
				return "", fmt.Errorf("%s's (%s) describes %s, but none of its methods' commands has that noun. Describe %s instead",
					svc.Desc.FullName(), nounsOption, name, list(nouns, "and"))
			}
			if help == "" {
				return "", fmt.Errorf("%s's (%s) gives %s no help. Say what %s are for", svc.Desc.FullName(), nounsOption, name, words(name))
			}
			helps[name] = help
		}
	}
	if help, ok := helps[noun]; ok {
		return help, nil
	}
	if len(nouns) > 1 {
		return "", fmt.Errorf("%s's methods' commands have the nouns %s, so its comment can't describe each. Describe %s with the (%s) option",
			svc.Desc.FullName(), list(nouns, "and"), noun, nounsOption)
	}
	return comment(svc.Comments.Leading), nil
}

// commandNames replaces each method's name with its command, longer names
// first, so none is taken for the start of another.
func commandNames(methods []Method) *strings.Replacer {
	sorted := slices.Clone(methods)
	slices.SortFunc(sorted, func(a, b Method) int { return len(b.Method.GoName) - len(a.Method.GoName) })
	var pairs []string
	for _, m := range sorted {
		pairs = append(pairs, m.Method.GoName, "dockwell "+m.Noun+" "+m.Verb)
	}
	return strings.NewReplacer(pairs...)
}

// maxNounShort is how long a noun's short help may grow before it names
// fewer of its verbs.
const maxNounShort = 60

// nounShort lists a noun's verbs in the schema's order, as "Propose, get
// or apply changes". A noun with one verb has its method's help, and one
// with many lists only those of one word.
func nounShort(noun string, methods []Method, order map[*protogen.Method]int) string {
	if len(methods) == 1 {
		return methods[0].Short
	}
	methods = slices.Clone(methods)
	slices.SortFunc(methods, func(a, b Method) int { return order[a.Method] - order[b.Method] })
	var verbs, single []string
	for _, m := range methods {
		verbs = append(verbs, strings.ReplaceAll(m.Verb, "-", " "))
		if !strings.Contains(m.Verb, "-") {
			single = append(single, m.Verb)
		}
	}
	short := capitalize(list(verbs, "or") + " " + words(noun))
	if len(short) <= maxNounShort || len(single) == 0 {
		return short
	}
	return capitalize(list(single, "or")+" "+words(noun)) + fmt.Sprintf(", and %d more", len(verbs)-len(single))
}

// describe names and describes one method.
func (s *schema) describe(f *protogen.File, m *protogen.Method) (Method, error) {
	effect, xd, ok := s.option(m.Desc, effectOption)
	var value protoreflect.EnumValueDescriptor
	if ok {
		value = xd.Enum().Values().ByNumber(effect.Enum())
	}
	if value == nil || value.Name() == effectNone {
		return Method{}, fmt.Errorf("%s doesn't set (%s), so its command can't tell whether it changes anything. Set it", m.Desc.FullName(), effectOption)
	}
	rule, _ := proto.GetExtension(m.Desc.Options(), annotations.E_Http).(*annotations.HttpRule)
	noun, verb, err := Name(string(m.Desc.Name()), rule, m.Desc.IsStreamingServer() || m.Desc.IsStreamingClient())
	if err != nil {
		return Method{}, fmt.Errorf("%s: %w", m.Desc.FullName(), err)
	}
	if command, _, ok := s.option(m.Desc, commandOption); ok {
		fields := command.Message().Descriptor().Fields()
		if n := command.Message().Get(fields.ByName("noun")).String(); n != "" {
			noun = n
		}
		if v := command.Message().Get(fields.ByName("verb")).String(); v != "" {
			verb = v
		}
	}
	text := comment(m.Comments.Leading)
	short, long := Help(string(m.Desc.Name()), text)
	c := Method{
		Method: m, Noun: noun, Verb: verb, Short: short, Long: long, Package: f.GoImportPath, PackageName: f.GoPackageName,
		Effect: string(value.Name()), EffectIdent: s.goIdent(xd.Enum(), value),
	}
	if rule != nil {
		method, path := httpRule(rule)
		c.HTTP = method + " " + path
	}
	for _, f := range m.Input.Fields {
		c.Fields = append(c.Fields, Field{
			Path: string(f.Desc.Name()),
			Flag: s.flag(f.Desc),
			Help: oneLine(comment(f.Comments.Leading)),
			// A request's id names what it acts on, as REST paths bind it.
			Arg: f.Desc.Name() == "id" && f.Desc.Kind() == protoreflect.StringKind && !f.Desc.IsList(),
		})
	}
	return c, nil
}

// Name gives a method's noun and verb by the rules: the noun is the
// collection of its REST path, such as "servers" for /v1/servers/{id};
// the verb is the path's custom verb, such as "apply" for :apply, or the
// first word of the method's name, such as "list". A stream has no REST
// path, so its noun is the rest of its name, plural: WatchServers is
// servers watch, and WatchChange is changes watch.
func Name(method string, rule *annotations.HttpRule, stream bool) (noun, verb string, err error) {
	parts := camelWords(method)
	if len(parts) < 2 {
		return "", "", fmt.Errorf("can't tell a verb and a noun from the name %s. Name it as a verb and what it acts on, such as ListServers", method)
	}
	verb = strings.ToLower(parts[0])
	if rule == nil {
		if !stream {
			return "", "", fmt.Errorf("it has no google.api.http rule, which names its command. Give it one, as ADR 0015 says")
		}
		rest := parts[1:]
		last := rest[len(rest)-1]
		rest[len(rest)-1] = plural(last)
		return kebab(strings.Join(rest, "")), verb, nil
	}
	_, path := httpRule(rule)
	rest, ok := strings.CutPrefix(path, "/v1/")
	if !ok || rest == "" {
		return "", "", fmt.Errorf("its REST path %s isn't under /v1/", path)
	}
	segments := strings.Split(rest, "/")
	collection, _, _ := strings.Cut(segments[0], ":")
	if _, custom, ok := strings.Cut(segments[len(segments)-1], ":"); ok && !strings.HasSuffix(custom, "}") {
		verb = kebab(custom)
	}
	return kebab(collection), verb, nil
}

func httpRule(r *annotations.HttpRule) (method, path string) {
	switch p := r.GetPattern().(type) {
	case *annotations.HttpRule_Get:
		return "GET", p.Get
	case *annotations.HttpRule_Post:
		return "POST", p.Post
	case *annotations.HttpRule_Put:
		return "PUT", p.Put
	case *annotations.HttpRule_Patch:
		return "PATCH", p.Patch
	case *annotations.HttpRule_Delete:
		return "DELETE", p.Delete
	case *annotations.HttpRule_Custom:
		return p.Custom.GetKind(), p.Custom.GetPath()
	}
	return "", ""
}

// Kinds describes the commands for each kind in the spec an Edit carries:
// the fields of its oneof, in the order the schema gives them.
func Kinds(p *protogen.Plugin) ([]Kind, error) {
	s, err := newSchema(p)
	if err != nil {
		return nil, err
	}
	var spec *protogen.Message
	for _, f := range p.Files {
		for _, m := range f.Messages {
			if m.Desc.FullName() != editMessage {
				continue
			}
			for _, field := range m.Fields {
				if field.Desc.Name() == editSpecField {
					spec = field.Message
				}
			}
		}
	}
	if spec == nil {
		return nil, nil
	}
	var kinds *protogen.Oneof
	for _, o := range spec.Oneofs {
		if o.Desc.Name() == specKindsOneof {
			kinds = o
		}
	}
	if kinds == nil {
		return nil, fmt.Errorf("%s has no oneof %s, so the generator can't find its kinds", spec.Desc.FullName(), specKindsOneof)
	}
	var out []Kind
	for _, f := range kinds.Fields {
		if f.Message == nil {
			return nil, fmt.Errorf("%s isn't a message, so it can't be a kind's spec", f.Desc.FullName())
		}
		k := Kind{
			Field: string(f.Desc.Name()),
			Noun:  kebab(plural(string(f.Desc.Name()))),
			Short: strings.TrimSuffix(firstSentence(comment(f.Comments.Leading)), "."),
			Long:  reflow(comment(f.Message.Comments.Leading)),
		}
		k.Fields = s.specFields(f.Message, "", 0)
		out = append(out, k)
	}
	return out, nil
}

// specFields flattens a spec's fields into flags: a message field that
// isn't repeated becomes its own fields, such as app.image; the rest are
// leaves.
func (s *schema) specFields(m *protogen.Message, prefix string, depth int) []Field {
	var out []Field
	for _, f := range m.Fields {
		path := prefix + string(f.Desc.Name())
		if f.Message != nil && !f.Desc.IsList() && !f.Desc.IsMap() && !wellKnown(f.Message) && depth < 3 {
			out = append(out, s.specFields(f.Message, path+".", depth+1)...)
			continue
		}
		sensitive, _, _ := s.option(f.Desc, sensitiveOption)
		out = append(out, Field{Path: path, Flag: s.flag(f.Desc), Help: oneLine(comment(f.Comments.Leading)), Sensitive: sensitive.IsValid() && sensitive.Bool()})
	}
	return out
}

func wellKnown(m *protogen.Message) bool {
	return strings.HasPrefix(string(m.Desc.FullName()), "google.protobuf.")
}

// Help gives a method's short help and its long help from its comment,
// each paragraph on one line.
// The comment starts with the method's name and a verb, as "ListServers
// returns every server"; the help starts with the verb as a command, as
// "Return every server".
func Help(name, text string) (short, long string) {
	if text == "" {
		return "", ""
	}
	paras := paragraphs(text)
	first := firstSentence(paras[0])
	rest := strings.TrimSpace(strings.TrimPrefix(paras[0], first))
	imperative := first
	if after, ok := strings.CutPrefix(first, name+" "); ok {
		verb, tail, _ := strings.Cut(after, " ")
		imperative = capitalize(Imperative(verb))
		if tail != "" {
			imperative += " " + tail
		}
	}
	short = firstClause(strings.TrimSuffix(imperative, "."))
	long = imperative
	if rest != "" {
		long += " " + rest
	}
	for _, p := range paras[1:] {
		long += "\n\n" + p
	}
	return short, long
}

// firstClause cuts a sentence at the end of its first clause, so a short
// help names one thing: at a comma, semicolon or colon, or at "and" before
// a verb, as in "Plan a set of edits and records them".
func firstClause(s string) string {
	cut := len(s)
	for _, sep := range []string{", ", "; ", ": "} {
		if i := strings.Index(s, sep); i >= 0 && i < cut {
			cut = i
		}
	}
	words := strings.Fields(s[:cut])
	for i := 1; i+1 < len(words); i++ {
		next := words[i+1]
		if words[i] == "and" && strings.HasSuffix(next, "s") && !strings.HasSuffix(next, "ss") {
			return strings.Join(words[:i], " ")
		}
	}
	return s[:cut]
}

// Imperative turns a verb in the third person, as a comment starts, into
// a command: "returns" is "return", "carries" "carry", "watches" "watch".
func Imperative(verb string) string {
	switch {
	case verb == "does" || verb == "goes":
		return strings.TrimSuffix(verb, "es")
	case verb == "is":
		return "be"
	case verb == "has":
		return "have"
	case strings.HasSuffix(verb, "ies") && len(verb) > 4:
		return strings.TrimSuffix(verb, "ies") + "y"
	case strings.HasSuffix(verb, "sses"), strings.HasSuffix(verb, "shes"), strings.HasSuffix(verb, "ches"),
		strings.HasSuffix(verb, "xes"), strings.HasSuffix(verb, "zes"):
		return strings.TrimSuffix(verb, "es")
	case strings.HasSuffix(verb, "s") && !strings.HasSuffix(verb, "ss"):
		return strings.TrimSuffix(verb, "s")
	}
	return verb
}

// comment is a comment's text without its markers: lines trimmed, with a
// blank line between paragraphs.
func comment(c protogen.Comments) string {
	lines := strings.Split(strings.TrimRight(string(c), "\n"), "\n")
	for i, l := range lines {
		lines[i] = strings.TrimSpace(l)
	}
	return strings.TrimSpace(strings.Join(lines, "\n"))
}

// paragraphs splits text at blank lines, each paragraph on one line. A
// line that starts a list item, with "- " or "* ", keeps its own line.
func paragraphs(text string) []string {
	var out []string
	var cur []string
	flush := func() {
		if len(cur) > 0 {
			out = append(out, strings.Join(cur, " "))
			cur = nil
		}
	}
	for _, l := range strings.Split(text, "\n") {
		switch {
		case l == "":
			flush()
		case strings.HasPrefix(l, "- ") || strings.HasPrefix(l, "* "):
			flush()
			cur = append(cur, l)
		default:
			cur = append(cur, l)
		}
	}
	flush()
	return out
}

// oneLine is text on one line, for a flag's help.
func oneLine(text string) string { return strings.Join(paragraphs(text), " ") }

// reflow wraps each paragraph of text at wrapWidth.
func reflow(text string) string {
	var out []string
	for _, p := range paragraphs(text) {
		var b strings.Builder
		width := 0
		for _, w := range strings.Fields(p) {
			n := len([]rune(w))
			if width > 0 && width+1+n > wrapWidth {
				b.WriteString("\n")
				width = 0
			} else if width > 0 {
				b.WriteString(" ")
				width++
			}
			b.WriteString(w)
			width += n
		}
		out = append(out, b.String())
	}
	return strings.Join(out, "\n\n")
}

// firstSentence is text up to and including the first full stop that
// ends a sentence.
func firstSentence(text string) string {
	text = oneLine(text)
	for i := 0; i < len(text); i++ {
		if text[i] == '.' && (i+1 == len(text) || text[i+1] == ' ') {
			return text[:i+1]
		}
	}
	return text
}

// camelWords splits a CamelCase name into its words.
func camelWords(s string) []string {
	var out []string
	start := 0
	runes := []rune(s)
	for i := 1; i < len(runes); i++ {
		if unicode.IsUpper(runes[i]) && (unicode.IsLower(runes[i-1]) || i+1 < len(runes) && unicode.IsLower(runes[i+1])) {
			out = append(out, string(runes[start:i]))
			start = i
		}
	}
	return append(out, string(runes[start:]))
}

// kebab writes a name in camelCase, PascalCase or snake_case in kebab-case,
// as commands and flags are: "beginPasskeySignIn" is
// "begin-passkey-sign-in".
func kebab(s string) string {
	var parts []string
	for _, p := range strings.Split(s, "_") {
		for _, w := range camelWords(p) {
			if w != "" {
				parts = append(parts, strings.ToLower(w))
			}
		}
	}
	return strings.Join(parts, "-")
}

// plural gives a noun's plural, keeping one that is plural already.
func plural(s string) string {
	switch {
	case strings.HasSuffix(s, "s"):
		return s
	case strings.HasSuffix(s, "y") && len(s) > 1 && !strings.ContainsRune("aeiou", rune(s[len(s)-2])):
		return s[:len(s)-1] + "ies"
	}
	return s + "s"
}

// acronyms are words help writes in capitals.
var acronyms = map[string]string{"api": "API", "totp": "TOTP", "id": "ID"}

// words writes a kebab-case noun as words, for help: "api-tokens" is "API
// tokens".
func words(noun string) string {
	parts := strings.Split(noun, "-")
	for i, p := range parts {
		if a, ok := acronyms[p]; ok {
			parts[i] = a
		}
	}
	return strings.Join(parts, " ")
}

// list joins words as a sentence does: "a, b or c".
func list(items []string, conjunction string) string {
	switch len(items) {
	case 0:
		return ""
	case 1:
		return items[0]
	}
	return strings.Join(items[:len(items)-1], ", ") + " " + conjunction + " " + items[len(items)-1]
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

// write writes the generated file.
func write(g *protogen.GeneratedFile, methods []Method, nouns []Noun, kinds []Kind) {
	g.P(headerLicense)
	g.P()
	g.P(generatedNotice)
	g.P()
	g.P("// Package apicmd describes the dockwell CLI's API commands, generated from")
	g.P("// the schema in proto/ by protoc-gen-dockwell-cli. Run make generate after")
	g.P("// changing the schema. See docs/adr/0019-a-cli-generated-from-the-schema.md.")
	g.P("package apicmd")
	g.P()
	ident := func(name string) protogen.GoIdent { return apicli.Ident(name) }

	g.P("// Methods describes a command for each method of ", Package, ", by noun and")
	g.P("// verb.")
	g.P("func Methods() []*", ident("Method"), " {")
	g.P("return []*", ident("Method"), "{")
	for _, m := range methods {
		in, out := m.Method.Input.GoIdent, m.Method.Output.GoIdent
		procedure := connectIdent(m)
		caller := "Unary"
		if m.Method.Desc.IsStreamingServer() {
			caller = "ServerStream"
		}
		g.P("{")
		g.P("Name: ", strconv.Quote(string(m.Method.Desc.FullName())), ",")
		g.P("Procedure: ", procedure, ",")
		if m.HTTP != "" {
			g.P("HTTP: ", strconv.Quote(m.HTTP), ",")
		}
		g.P("Noun: ", strconv.Quote(m.Noun), ",")
		g.P("Verb: ", strconv.Quote(m.Verb), ",")
		g.P("Short: ", strconv.Quote(m.Short), ",")
		g.P("Long: ", strconv.Quote(m.Long), ",")
		g.P("Effect: ", m.EffectIdent, ",")
		writeFields(g, m.Fields)
		if m.Method.Desc.IsStreamingClient() {
			g.P("// Client streams have no command yet.")
		} else {
			g.P("Call: ", apicli.Ident(caller), "[", in, ", ", out, "](", procedure, "),")
		}
		g.P("},")
	}
	g.P("}")
	g.P("}")
	g.P()

	g.P("// Nouns describes each noun the methods' commands have.")
	g.P("func Nouns() []", ident("Noun"), " {")
	g.P("return []", ident("Noun"), "{")
	for _, n := range nouns {
		g.P("{Name: ", strconv.Quote(n.Name), ", Short: ", strconv.Quote(n.Short), ", Long: ", strconv.Quote(n.Long), "},")
	}
	g.P("}")
	g.P("}")
	g.P()

	g.P("// Kinds describes the commands for each kind of resource an edit's spec")
	g.P("// can hold.")
	g.P("func Kinds() []*", ident("Kind"), " {")
	g.P("return []*", ident("Kind"), "{")
	for _, k := range kinds {
		g.P("{")
		g.P("Field: ", strconv.Quote(k.Field), ",")
		g.P("Noun: ", strconv.Quote(k.Noun), ",")
		g.P("Short: ", strconv.Quote(k.Short), ",")
		g.P("Long: ", strconv.Quote(k.Long), ",")
		writeFields(g, k.Fields)
		g.P("},")
	}
	g.P("}")
	g.P("}")
}

func writeFields(g *protogen.GeneratedFile, fields []Field) {
	if len(fields) == 0 {
		return
	}
	g.P("Fields: []", apicli.Ident("Field"), "{")
	for _, f := range fields {
		line := []any{"{Path: ", strconv.Quote(f.Path)}
		if f.Flag != "" {
			line = append(line, ", Flag: ", strconv.Quote(f.Flag))
		}
		if f.Help != "" {
			line = append(line, ", Help: ", strconv.Quote(f.Help))
		}
		if f.Arg {
			line = append(line, ", Arg: true")
		}
		if f.Sensitive {
			line = append(line, ", Sensitive: true")
		}
		line = append(line, "},")
		g.P(line...)
	}
	g.P("},")
}

// connectIdent is the constant connect-go generates for a method's
// procedure, in the package it puts beside its file's.
func connectIdent(m Method) protogen.GoIdent {
	return protogen.GoImportPath(string(m.Package) + "/" + string(m.PackageName) + connectPackage).Ident(m.Method.Parent.GoName + m.Method.GoName + "Procedure")
}
