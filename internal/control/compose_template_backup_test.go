func TestComposeTemplatesSurviveStoreBackup(t *testing.T) {
	t.Parallel()
	eachStoreParallel(t, func(t *testing.T, backend store.Backend) {
		f := startFull(t, backend, nil)
		b := signedIn(t, f)
		changes := changeClient(b, b.origin)
		project := resourceIn(t, apply(t, changes, propose(t, changes, "Make a library", &v1.Edit{
			Resource: &v1.ResourceRef{Kind: "project", Name: "restore-library"},
			Spec:     &spec.Spec{Kind: &spec.Spec_Project{Project: &spec.Project{}}},
		})), "project")
		ref := &v1.ResourceRef{Kind: "compose.template", Scope: project, Name: "web"}
		save := func(base int64, description string) string {
			t.Helper()
			change := propose(t, changes, "Save a template", &v1.Edit{
				Resource: ref, BaseRevision: base,
				Spec: &spec.Spec{Kind: &spec.Spec_ComposeTemplate{ComposeTemplate: &spec.ComposeTemplate{
					ComposeYaml: "services:\n  web:\n    image: nginx:1.27\n", Description: description,
				}}},
			})
			if len(change.GetPlan().GetServers()) != 0 {
				t.Fatal("saving a template should require no server calls")
			}
			applyConfirmed(t, changes, change)
			return resourceIn(t, change, "compose.template")
		}
		id := save(0, "First")
		save(1, "Second")
		restored := restoreTemplateTestStore(t, f.db, backend)
		defer restored.Close()
		err := restored.View(t.Context(), func(tx *store.Tx) error {
			rows, err := tx.PageRevisions(t.Context(), id, 0, 10)
			if err != nil {
				return err
			}
			if len(rows) != 2 || rows[0].Scope != project || rows[1].Scope != project {
				t.Fatalf("restored template revisions: %v", rows)
			}
			for i, want := range []string{"Second", "First"} {
				var definition spec.ComposeTemplate
				if err := proto.Unmarshal(rows[i].Spec, &definition); err != nil {
					return err
				}
				if definition.GetDescription() != want || !strings.Contains(definition.GetComposeYaml(), "nginx:1.27") {
					t.Fatalf("restored revision %d: %v", rows[i].Revision, &definition)
				}
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	})
}

func restoreTemplateTestStore(t *testing.T, location string, backend store.Backend) *store.DB {
	t.Helper()
	target := storetest.New(t, backend)
	if backend == store.SQLite {
		conn, err := sql.Open("sqlite", location)
		if err != nil {
			t.Fatal(err)
		}
		defer conn.Close()
		if _, err := conn.ExecContext(t.Context(), "VACUUM INTO ?", target); err != nil {
			t.Fatal(err)
		}
	} else {
		restoreTemplateTestPostgres(t, location, target)
	}
	db, err := store.OpenExisting(t.Context(), target)
	if err != nil {
		t.Fatal(err)
	}
	return db
}

func restoreTemplateTestPostgres(t *testing.T, location, target string) {
	t.Helper()
	for _, name := range []string{"pg_dump", "psql"} {
		if _, err := exec.LookPath(name); err != nil {
			t.Skipf("the PostgreSQL backup round trip needs %s", name)
		}
	}
	schema := func(location string) (string, string) {
		u, err := url.Parse(location)
		if err != nil {
			t.Fatal(err)
		}
		q := u.Query()
		name := q.Get("search_path")
		q.Del("search_path")
		u.RawQuery = q.Encode()
		return name, u.String()
	}
	source, connection := schema(location)
	dest, _ := schema(target)
	dump, err := exec.CommandContext(t.Context(), "pg_dump", "--no-owner", "--no-privileges", "--clean", "--if-exists", "--schema", source, connection).CombinedOutput()
	if err != nil {
		if strings.Contains(string(dump), "server version mismatch") {
			t.Skip("pg_dump is older than the PostgreSQL test server")
		}
		t.Fatalf("pg_dump: %v: %s", err, dump)
	}
	// Both schema names are randomly generated by storetest. Keep the source
	// untouched and restore into the test's separately cleaned-up schema.
	cmd := exec.CommandContext(t.Context(), "psql", "-X", "--set=ON_ERROR_STOP=1", connection)
	cmd.Stdin = strings.NewReader(strings.ReplaceAll(string(dump), source, dest))
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("restore: %v: %s", err, out)
	}
}
